/** Normalize state name for matching (e.g. from API to our INDIAN_STATES) */
function normalizeState(s: string): string {
  return STATE_ALIAS[s] ?? s
}

/** Get cities filtered by state; returns options for SearchableSelect */
export function getCityOptionsForState(stateName: string): { value: string; label: string }[] {
  const normalized = normalizeState(stateName)
  const list = INDIAN_CITIES.filter((c) => normalizeState(c.state) === normalized)
  const seen = new Set<string>()
  return list
    .filter((c) => {
      if (seen.has(c.name)) return false
      seen.add(c.name)
      return true
    })
    .map((c) => ({ value: c.name, label: c.name }))
}

/** All unique city names for global search (state not selected) */
export function getAllCityOptions(): { value: string; label: string }[] {
  const seen = new Set<string>()
  return INDIAN_CITIES.filter((c) => {
    if (seen.has(c.name)) return false
    seen.add(c.name)
    return true
  }).map((c) => ({ value: c.name, label: `${c.name}, ${c.state}` }))
}
